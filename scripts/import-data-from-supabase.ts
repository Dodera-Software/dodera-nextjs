/**
 * import-data-from-supabase.ts
 * ----------------------------
 * ONE-TIME migration script: copies all rows of the 11 app tables from
 * Supabase (via the PostgREST API, using the service key — no direct DB
 * password needed) into the new Postgres (DATABASE_URL).
 *
 * - Preserves original id values (OVERRIDING SYSTEM VALUE) and resets
 *   the identity sequences afterwards.
 * - Refuses to touch any target table that already contains rows, so it
 *   can be re-run safely after a partial failure.
 *
 * Required env vars:
 *   DATABASE_URL          — the NEW Postgres connection string
 *   SUPABASE_URL          — the OLD Supabase project URL
 *   SUPABASE_SECRET_KEY   — the OLD Supabase service-role/secret key
 *
 * Usage:
 *   npx tsx --env-file=.env scripts/import-data-from-supabase.ts
 */

import { sql } from "drizzle-orm";
