async function fetchAllRows(baseUrl: string, key: string, spec: TableSpec): Promise<Row[]> {
    const rows: Row[] = [];
    for (let offset = 0; ; offset += PAGE_SIZE) {
        const url = `${baseUrl}/rest/v1/${spec.name}?select=*&order=${spec.orderBy}.asc`;
        const res = await fetch(url, {
            headers: {
                apikey: key,
                Authorization: `Bearer ${key}`,
                Range: `${offset}-${offset + PAGE_SIZE - 1}`,
            },
        });
        if (!res.ok) {
            throw new Error(`${spec.name}: fetch failed (${res.status} ${res.statusText}) — ${await res.text()}`);
        }
        const page = (await res.json()) as Row[];
        rows.push(...page);
        if (page.length < PAGE_SIZE) return rows;
    }
}

async function main() {
    const supabaseUrl = process.env.SUPABASE_URL?.replace(/\/$/, "");
    const supabaseKey = process.env.SUPABASE_SECRET_KEY;
    if (!supabaseUrl || !supabaseKey) {
        console.error("Error: SUPABASE_URL and SUPABASE_SECRET_KEY must be set in .env");
        process.exit(1);
    }

    const { db, pool } = getDb();

    try {
        for (const spec of TABLES) {
            const [{ existing }] = (await db.execute(
                sql`select count(*)::int as existing from ${spec.table}`,
            )).rows as [{ existing: number }];

            if (existing > 0) {
                console.log(`• ${spec.name}: target already has ${existing} row(s) — skipping.`);
                continue;
            }

            const rows = await fetchAllRows(supabaseUrl, supabaseKey, spec);
            if (rows.length === 0) {
                console.log(`• ${spec.name}: 0 rows in Supabase — nothing to copy.`);
                continue;
            }

            for (let i = 0; i < rows.length; i += 500) {
                const chunk = rows.slice(i, i + 500).map(spec.map);
                if (spec.identity) {
                    await db.insert(spec.table).overridingSystemValue().values(chunk);
                } else {
                    await db.insert(spec.table).values(chunk);
                }
            }

            if (spec.identity) {
                await db.execute(sql`
                    select setval(
                        pg_get_serial_sequence(${spec.name}, 'id'),
                        coalesce((select max(id) from ${sql.raw(`"${spec.name}"`)}), 0) + 1,
                        false
                    )
                `);
            }

            console.log(`✓ ${spec.name}: copied ${rows.length} row(s).`);
        }

        console.log("\nDone. Now verify counts, then run: npm run migrate:cvs");
    } finally {
        await pool.end();
    }
}

main().catch((err) => {
    console.error("Unexpected error:", err);
    process.exit(1);
});
