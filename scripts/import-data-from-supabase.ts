const PAGE_SIZE = 1000;

/* eslint-disable @typescript-eslint/no-explicit-any */
type Row = Record<string, any>;

const date = (v: string | null | undefined): Date | null => (v ? new Date(v) : null);

interface TableSpec {
    /** Table name in Supabase (snake_case) */
    name: string;
    table: PgTable;
    /** Column used for stable pagination ordering */
    orderBy: string;
    /** Whether the table has a GENERATED ALWAYS identity id */
    identity: boolean;
    /** Map a PostgREST JSON row to drizzle insert values */
    map: (r: Row) => Row;
}

